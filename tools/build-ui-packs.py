#!/usr/bin/env python3
"""Package the checked-in Nebula CSS without modifying it or fetching assets.

Run from any directory. Output is deterministic: fixed ZIP timestamps, stored
entries and stable filenames. The CSS stays at css/nebula.css inside each ZIP.
No pack code is executed, and the site never loads these stylesheets.
"""
from pathlib import Path
import hashlib
import io
import sys
import json
import zipfile

ROOT = Path(__file__).resolve().parents[1]
THEMES = [
    ('Cosmic_Purple', '#9e53ed'),
    ('Emerald_Green', '#41d987'),
    ('Imperial_Gold', '#e8bb49'),
    ('Inferno_Red', '#ef5656'),
    ('Ocean_Blue', '#459aee'),
    ('Original_Cyan', '#41dce8'),
    ('Sakura_Pink', '#ef8abd'),
    ('Solar_Orange', '#ef9841'),
]

CHECK = '--check' in sys.argv[1:]
packs = []
for theme, color in THEMES:
    family = 'nebula-' + theme.lower().replace('_', '-')
    name = 'Nebula ' + theme.replace('_', ' ')
    for font in ['normal', 'pixel']:
        source = 'Nebula_' + theme + ('_Pixel' if font == 'pixel' else '')
        directory = ROOT / 't-packs' / source
        paths = sorted(path for path in directory.rglob('*') if path.is_file())
        if [path.relative_to(directory).as_posix() for path in paths] != ['css/nebula.css']:
            raise ValueError(f'Unexpected source layout: {source}')
        css = paths[0].read_bytes()
        if b'NEBULA UI V5' not in css:
            raise ValueError(f'Check the advertised version before publishing: {source}')
        filename = family + '-font-' + font + '.zip'
        destination = ROOT / 't-packs' / filename
        buffer = io.BytesIO()
        with zipfile.ZipFile(buffer, 'w', compression=zipfile.ZIP_STORED) as archive:
            entry = zipfile.ZipInfo('css/nebula.css', date_time=(2026, 1, 1, 0, 0, 0))
            entry.create_system = 3
            entry.external_attr = 0o100644 << 16
            archive.writestr(entry, css)
        data = buffer.getvalue()
        if CHECK:
            if destination.read_bytes() != data:
                raise ValueError(f'Rebuild this archive: {filename}')
        else:
            destination.write_bytes(data)
        description_fr = 'Un thème Nebula pour l’interface uniquement : menus et éléments d’UI, sans textures de blocs. Choisissez font-normal ou font-pixel.'
        description_en = 'A Nebula theme for the interface only: menus and UI elements, without block textures. Choose font-normal or font-pixel.'
        packs.append(dict(
            id=family + '-font-' + font, category='ui', family=family,
            name=name, version='V5', font='font-' + font, color=color,
            description=description_fr,
            translations={'en': {'description': description_en}, 'fr': {'description': description_fr}},
            filename=filename, url='./t-packs/' + filename,
            source='./t-packs/' + source + '/css/nebula.css',
            expectedSizeBytes=len(data), sha256=hashlib.sha256(data).hexdigest(),
        ))

catalogue = (
    '// Generated by tools/build-ui-packs.py from the unchanged Nebula CSS sources.\n'
    '// V5 comes from their header, not an asserted game API version.\n'
    'export const UI_PACKS = ' + json.dumps(packs, ensure_ascii=False, indent=2) + ';\n'
)
output = ROOT / 'js' / 'ui-packs.js'
if CHECK:
    if output.read_text(encoding='utf-8') != catalogue:
        raise ValueError('Rebuild js/ui-packs.js')
else:
    output.write_text(catalogue, encoding='utf-8')
print(f'{"Verified" if CHECK else "Built"} {len(packs)} archives: {len(THEMES)} themes × 2 font variants.')
